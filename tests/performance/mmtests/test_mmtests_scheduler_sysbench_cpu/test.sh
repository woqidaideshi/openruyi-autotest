#!/bin/bash
# Functional test: kernel - mmtests - scheduler_sysbench_cpu
# MMTests: run-mmtests.sh --config configs/config-scheduler-sysbench-cpu
# Beakerlib-based test with lifecycle management

. /usr/share/beakerlib/beakerlib.sh || exit 1
. "$(dirname "$0")/../lib.sh"

rlJournalStart
    rlPhaseStartSetup "环境准备"
        mmtestsSetup
        TmpDir=$(mktemp -d)
        rlRun "cd $TmpDir" 0 "进入临时测试目录"
    rlPhaseEnd

    rlPhaseStartTest "MMTests - scheduler_sysbench_cpu"
        rlRun "_mmtestsRunCase config-scheduler-sysbench-cpu" 0 "执行 MMTests config-scheduler-sysbench-cpu"
    rlPhaseEnd

    rlPhaseStartCleanup "清理测试环境"
        rlRun "cd /" 0 "离开测试目录"
        [ -n "$TmpDir" ] && [ -d "$TmpDir" ] && rlRun "rm -rf $TmpDir" 0 "清理"
    rlPhaseEnd

    rlJournalPrintText
rlJournalEnd